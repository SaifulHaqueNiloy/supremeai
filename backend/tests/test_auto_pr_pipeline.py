import pytest

from tools.code.auto_pr_pipeline import AutoPRPipeline


@pytest.mark.asyncio
async def test_auto_pr_pipeline_success():
    pipeline = AutoPRPipeline()
    result = await pipeline.create_patch_pr(
        branch_name="fix/patch-circuit-breaker",
        file_path="backend/core/resilience/circuit_breaker.py",
        patch_code="def safe_patch(): return True",
        pr_title="Fix: Patch Circuit Breaker Latency",
        pr_description="Automated AI patch generated by AutoHealer.",
    )
    assert result["status"] in ("success", "failed")


@pytest.mark.asyncio
async def test_auto_pr_pipeline_rejection(monkeypatch):
    pipeline = AutoPRPipeline()

    async def mock_scan_code(code):
        return {"is_safe": False, "reason": "Syntax or security vulnerability detected"}

    from core.security.guardian_ai import guardian_ai

    monkeypatch.setattr(guardian_ai, "scan_code", mock_scan_code)

    result = await pipeline.create_patch_pr(
        branch_name="fix/unsafe-patch",
        file_path="backend/core/main.py",
        patch_code="eval('bad_code')",
        pr_title="Fix: Malicious patch",
        pr_description="Testing unsafe patch rejection.",
    )
    assert result["status"] == "failed"
    assert "Guardian AI rejected patch" in result["reason"]
